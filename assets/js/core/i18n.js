let lang = 'ar';
export function setUiLang(l) { lang = l === 'en' ? 'en' : 'ar'; }
export function getUiLang() { return lang; }
export function isRTL() { return lang === 'ar'; }

export function t(key, vars = null) {
  const entry = DICT[key];
  let s = entry ? (lang === 'en' ? entry[1] : entry[0]) : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  return s;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    const txt = t(key);
    if (txt && txt !== key) el.textContent = txt;
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const txt = t(el.dataset.i18nTitle);
    if (txt) el.setAttribute('title', txt);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const txt = t(el.dataset.i18nPlaceholder);
    if (txt) el.setAttribute('placeholder', txt);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const txt = t(el.dataset.i18nAria);
    if (txt) el.setAttribute('aria-label', txt);
  });
}

export function hasKey(key) { return !!DICT[key]; }
