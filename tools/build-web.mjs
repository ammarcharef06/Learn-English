import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..');
const out = resolve(root, 'www');
const rootFiles = [
  '.nojekyll',
  'index.html',
  'zero.html',
  'manifest.webmanifest',
  'manifest-zero.webmanifest',
  'service-worker.js',
];
const nativeScripts = [
  '<script src="./capacitor.js"></script>',
  '<script src="./assets/js/vendor/local-notifications.js"></script>',
].join('\n  ');

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
for (const file of rootFiles) {
  const content = await readFile(resolve(root, file), 'utf8');
  const nativeContent = content.replace('</body>', `  ${nativeScripts}\n</body>`);
  await writeFile(resolve(out, file), nativeContent);
}
await cp(resolve(root, 'assets'), resolve(out, 'assets'), { recursive: true });
await cp(resolve(root, 'node_modules/@capacitor/core/dist/capacitor.js'), resolve(out, 'capacitor.js'));
await mkdir(resolve(out, 'assets/js/vendor'), { recursive: true });
await build({
  entryPoints: [resolve(root, 'node_modules/@capacitor/local-notifications/dist/esm/index.js')],
  bundle: true,
  format: 'iife',
  globalName: 'CapacitorLocalNotificationsBundle',
  platform: 'browser',
  target: ['es2020'],
  outfile: resolve(out, 'assets/js/vendor/local-notifications.js'),
});
await writeFile(resolve(out, '.capacitor-build'), 'Generated by npm run build:web\n');
console.log(`Android web assets and local-notification plugin prepared in ${out}`);
